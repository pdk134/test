def augment_file(path):
    with open(path, encoding="utf-8") as f:
        paras = [p.strip() for p in f.read().split("\n") if p.strip()]
    out = []
    for p in paras:
        out.append(p)  # 原句
        # 生成一个变体
        new = p
        hits = [s for s in SYNONYMS if s[0] in new]
        random.shuffle(hits)
        for old, repls in hits[: random.randint(1, 3)]:
            new = new.replace(old, random.choice(repls), 1)
        if new != p:
            out.append(new)
    return out


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    total = 0
    for f in sorted(glob.glob(os.path.join(SEED_DIR, "*.txt"))):
        name = os.path.basename(f)
        lines = augment_file(f)
        with open(os.path.join(OUT_DIR, name), "w", encoding="utf-8") as g:
            g.write("\n".join(lines) + "\n")
        total += len(lines)
        print("  %-22s %4d 段（原 %d + 变体 %d）"
              % (name, len(lines), len(lines) // 2 + len(lines) % 2, len(lines) // 2))
    # 姓氏句单独一个文件
    with open(os.path.join(OUT_DIR, "z_names.txt"), "w", encoding="utf-8") as g:
        g.write("\n".join(NAME_SENTENCES) + "\n")
    total += len(NAME_SENTENCES)
    print("  %-22s %4d 段" % ("z_names.txt", len(NAME_SENTENCES)))
    print("增强完成，共 %d 段" % total)


if __name__ == "__main__":
    main()
