def 造句子(主, 地, 物, 动, 形):
    t = random.random()
    if t < 0.06:   return f"{random.choice(事实)}"
    if t < 0.14:  return f"{random.choice(时间)}，{主}在{random.choice(地点)}{random.choice(副词)}{random.choice(活动)}。"
